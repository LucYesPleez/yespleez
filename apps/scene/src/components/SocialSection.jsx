/**
 * Renders a list of social/link rows with N/A toggles.
 *
 * links: Array of { icon, key, value, onChange, placeholder, type?, noNa? }
 *   icon        — key into ICONS map (sc, mc, ig, yt, fb, tt, spotify, bc, bp,
 *                 headphones, email, web)
 *   key         — naFields key for this row
 *   value       — current input value
 *   onChange    — input onChange handler
 *   placeholder — input placeholder text
 *   type        — input type attribute (default 'text')
 *   noNa        — if true, N/A button is omitted (e.g. demo mix link)
 */
export default function SocialSection({ links, naFields, onToggleNa, inputClass, rowClass, iconClass }) {
  return (
    <>
      {links.map(({ icon, key, value, onChange, placeholder, type = 'text', noNa = false }) => {
        const na = !noNa && naFields.has(key);
        return (
          <div key={key} className={rowClass}>
            <div className={iconClass}>{ICONS[icon]}</div>
            <input
              className={inputClass}
              type={type}
              value={value}
              onChange={onChange}
              placeholder={placeholder}
              autoCapitalize="none"
              disabled={na}
              style={{ opacity: na ? 0.4 : 1 }}
            />
            {!noNa && (
              <button type="button" onClick={() => onToggleNa(key)} style={NA_BTN_STYLE(na)}>
                N/A
              </button>
            )}
          </div>
        );
      })}
    </>
  );
}
